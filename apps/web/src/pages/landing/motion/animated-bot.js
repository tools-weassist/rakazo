  // Blink and glance scheduler: one timer for every bot on the page, only for bots on screen.
  var live = new Set(), visible = new Set(), io = null, timer = null;
  function track(svg) {
    live.add(svg);
    if (!io && 'IntersectionObserver' in root) {
      io = new IntersectionObserver(function (es) {
        es.forEach(function (e) { e.isIntersecting ? visible.add(e.target) : visible.delete(e.target); });
      });
    }
    if (io) io.observe(svg); else visible.add(svg);
    if (!timer) tick();
  }
  function tick() {
    timer = setTimeout(function () {
      if (!document.hidden) {
        visible.forEach(function (svg) {
          if (!svg.isConnected) { live.delete(svg); visible.delete(svg); return; }
          var r = Math.random();
          if (r < 0.28) blink(svg);
          else if (r < 0.36 && svg.getAttribute('data-mood') === 'idle') look(svg, Math.random() * 2 - 1, Math.random() * 1.2 - 0.6, 1400);
        });
      }
      tick();
    }, 900);
  }
  function blink(svg) {
    svg.classList.add('is-blink');
    setTimeout(function () { svg.classList.remove('is-blink'); }, 150);
    if (Math.random() < 0.2) setTimeout(function () { blink(svg); }, 260); // occasional double blink
  }
  function look(svg, x, y, holdMs) {
    if (reduce) return;
    svg.style.setProperty('--lx', (x * 4).toFixed(2) + 'px');
    svg.style.setProperty('--ly', (y * 3).toFixed(2) + 'px');
    if (holdMs) setTimeout(function () { look(svg, 0, 0); }, holdMs);
  }
